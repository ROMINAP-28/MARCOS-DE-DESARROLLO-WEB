-- Si no hay exactamente un responsable por proyecto, se cancela sin modificar datos.

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM proyecto p
        LEFT JOIN proyecto_usuario pu ON pu.id_proyecto = p.id_proyecto
                                   AND lower(pu.rol) = 'responsable'
        GROUP BY p.id_proyecto HAVING count(pu.id_usuario) <> 1
    ) THEN
        RAISE EXCEPTION 'Cada proyecto debe tener exactamente un responsable en proyecto_usuario';
    END IF;
END $$;

ALTER TABLE proyecto ADD COLUMN id_responsable integer;
ALTER TABLE proyecto ADD COLUMN fecha_creacion timestamp without time zone;

UPDATE proyecto p SET id_responsable = pu.id_usuario,
                      fecha_creacion = coalesce(pu.fecha_asignacion, CURRENT_TIMESTAMP)
FROM proyecto_usuario pu
WHERE p.id_proyecto = pu.id_proyecto AND lower(pu.rol) = 'responsable';

ALTER TABLE proyecto ALTER COLUMN id_responsable SET NOT NULL;
ALTER TABLE proyecto ALTER COLUMN fecha_creacion SET NOT NULL;
ALTER TABLE proyecto ADD CONSTRAINT fk_proyecto_responsable
    FOREIGN KEY (id_responsable) REFERENCES usuario(id_usuario);
CREATE INDEX idx_proyecto_responsable ON proyecto(id_responsable);

-- La fecha histórica de asignación no existe: fecha_creacion es la mejor aproximación disponible.
ALTER TABLE tarea ADD COLUMN fecha_asignacion timestamp without time zone;
UPDATE tarea SET fecha_asignacion = fecha_creacion;

-- Mensaje breve y contenido detallado son campos distintos. El detalle permanece opcional.
ALTER TABLE notificacion ADD COLUMN contenido varchar(255);

CREATE TABLE recurso (
    id_recurso integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_recurso varchar(150) NOT NULL,
    tipo_recurso varchar(100) NOT NULL,
    cantidad integer NOT NULL CHECK (cantidad >= 0),
    id_proyecto integer NOT NULL,
    CONSTRAINT fk_recurso_proyecto FOREIGN KEY (id_proyecto) REFERENCES proyecto(id_proyecto)
);
CREATE INDEX idx_recurso_proyecto ON recurso(id_proyecto);

CREATE TABLE reporte (
    id_reporte integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_reporte varchar(100) NOT NULL,
    fecha_generacion timestamp without time zone NOT NULL,
    estado varchar(30) NOT NULL,
    id_proyecto integer NOT NULL,
    id_usuario_generador integer NOT NULL,
    CONSTRAINT fk_reporte_proyecto FOREIGN KEY (id_proyecto) REFERENCES proyecto(id_proyecto),
    CONSTRAINT fk_reporte_usuario_generador FOREIGN KEY (id_usuario_generador) REFERENCES usuario(id_usuario)
);
CREATE INDEX idx_reporte_proyecto ON reporte(id_proyecto);
CREATE INDEX idx_reporte_usuario_generador ON reporte(id_usuario_generador);
